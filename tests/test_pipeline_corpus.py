"""Phase 2 acceptance on real hdl-bag output (see test_corpus.py for the corpus).

The pipeline that changes nothing must change nothing on every corpus design,
and must catch deliberately bad raw edits on the demo_ss sample. Tests never
write into the corpus cache: the session keeps edits in memory and output goes
to a temp directory.
"""

from __future__ import annotations

import json
import os
import re
from pathlib import Path

import pytest

import corpus
from hdl_vet.filelist import read_filelist
from hdl_vet.output import write_tree
from hdl_vet.session import HEADER_MARK, Session
from hdl_vet.slang_adapter import load

pytestmark = [
    pytest.mark.corpus,
    pytest.mark.skipif(
        not corpus.bag_available() and os.environ.get("HDL_VET_REQUIRE_CORPUS") != "1",
        reason="hdl-bag CLI (`bag`) not installed",
    ),
]

CACHE = Path(__file__).resolve().parent.parent / ".corpus"
DESIGNS = corpus.designs() if corpus.bag_available() else []
IDENT = re.compile(r"[A-Za-z_]\w*")


@pytest.fixture(scope="module", params=DESIGNS, ids=lambda d: d.id)
def built(request):
    return request.param.build(CACHE)


@pytest.fixture(scope="module")
def demo():
    (d,) = [d for d in DESIGNS if d.id == "demo_ss-flat"]
    return d.build(CACHE)


def test_no_op_pipeline_gives_an_identical_tree(built, tmp_path: Path):
    s = Session(built.filelist, top=built.top)
    r = s.finish()
    assert r.ok, r.report()
    assert r.files == {} and s.reloads == 0
    out = write_tree(s, r, tmp_path / "out")

    manifest = json.loads((out / "hdl-vet.json").read_text(encoding="utf-8"))
    assert manifest["changed"] == {} and manifest["top"] == built.top
    before = read_filelist(built.filelist)
    after = read_filelist(out / manifest["filelist"])
    assert len(after.files) == len(before.files)
    assert [p.name for p in after.files] == [p.name for p in before.files]
    assert all(a.read_bytes() == b.read_bytes() for a, b in zip(after.files, before.files, strict=True))
    assert len(after.incdirs) == len(before.incdirs) and after.defines == before.defines
    assert not any(HEADER_MARK in p.read_bytes() for p in after.files)

    copy = load(out / manifest["filelist"], top=built.top)
    assert copy.snapshot() == s.design.snapshot()
    assert len(copy.diagnostics()) == len(s.design.diagnostics())


def test_snapshot_covers_every_elaborated_instance(built):
    design = load(built.filelist, top=built.top)
    snap = design.snapshot()
    # The adapter enumerates instances with a walk that skips statements and
    # expressions. A scope kind it failed to descend into would hide instances
    # from sign-off, so compare it with the plain, exhaustive visit.
    assert design.elaborated_instance_paths() == design.elaborated_instance_paths(exhaustive=True)
    assert sorted(snap) == design.elaborated_instance_paths()
    assert len(snap) == design.elaborated_instance_count()
    assert snap[built.top].module == built.top and snap[built.top].connections == {}


# --- demo_ss ---------------------------------------------------------------------


def _first_instances(session: Session, top: str):
    insts = session.module(top).instances
    assert len(insts) >= 2
    return insts


def test_demo_rename_of_an_instance_passes(demo):
    s = Session(demo.filelist, top=demo.top)
    inst = _first_instances(s, demo.top)[0]
    new = inst.name + "_vet"
    s.splice(inst.path, inst.start, inst.start + len(inst.name), new.encode(), old=inst.name.encode())
    s.expect("instance-removed", f"{demo.top}.{inst.name}*")
    s.expect("instance-added", f"{demo.top}.{new}*")
    r = s.finish([("rename.py", "00" * 32)])
    assert r.new_diagnostics == [], r.report()
    assert r.ok, r.report()
    assert s.reloads == 1
    assert list(r.files) == [inst.path]


def test_demo_header_goes_after_the_generator_banner(demo):
    s = Session(demo.filelist, top=demo.top)
    m = s.module(demo.top)
    s.splice(m.path, m.body_end, m.body_end, b"// touched by a test\n")
    r = s.finish([("touch.py", "11" * 32)])
    assert r.ok, r.report()
    lines = r.files[m.path].split(b"\n")
    (at,) = [i for i, line in enumerate(lines) if line.startswith(HEADER_MARK)]
    assert at >= 1 and all(line.startswith(b"//") for line in lines[:at])
    assert any(b"Generated by hdl-bag" in line for line in lines[:at])
    assert not lines[at + 1].startswith(b"//")
    assert lines[at].rstrip(b"\r") == b"// Modified by hdl-vet; scripts: touch.py sha256:111111111111"


def test_demo_undeclared_signal_in_a_connection_is_caught(demo):
    s = Session(demo.filelist, top=demo.top)
    for inst in _first_instances(s, demo.top):
        conn = next((c for c in inst.connections if c.port and IDENT.fullmatch(c.expr)), None)
        if conn is not None:
            break
    else:
        pytest.fail("no instance in the top has a plain identifier connection")
    s.splice(inst.path, conn.start, conn.end, f".{conn.port}({conn.expr}_vet_typo)".encode())
    s.expect("*")
    r = s.finish()
    assert not r.ok
    assert {d.code for d in r.new_diagnostics} & {"ImplicitNet", "UndeclaredIdentifier"}, r.report()


def test_demo_module_swap_with_wrong_ports_is_caught(demo):
    s = Session(demo.filelist, top=demo.top)
    insts = _first_instances(s, demo.top)
    first = insts[0]
    other = next(i for i in insts if i.module != first.module)
    s.splice(first.path, first.module_start, first.module_end, other.module.encode(), old=first.module.encode())
    s.expect("*")
    r = s.finish()
    assert not r.ok
    assert any(d.severity == "error" for d in r.new_diagnostics), r.report()


def test_demo_changed_parameter_is_an_unexpected_change(demo):
    s = Session(demo.filelist, top=demo.top)
    target = None
    for name in s.design.modules():
        for inst in s.module(name).instances:
            ov = next((o for o in inst.param_overrides if o.name and o.value.isdigit()), None)
            if ov is not None:
                target = (inst, ov)
                break
        if target:
            break
    assert target is not None, "demo_ss must contain a literal named parameter override"
    inst, ov = target
    s.splice(inst.path, ov.start, ov.end, f".{ov.name}({int(ov.value) + 1})".encode())
    r = s.finish()
    assert not r.ok
    # Values are printed by slang ("32'd3"), so compare sides, not literals.
    hits = [
        c
        for c in r.unexpected_changes
        if c.kind == "param-changed" and c.name == ov.name and c.path.endswith("." + inst.name)
    ]
    assert hits and all(c.before != c.after for c in hits), r.report()
