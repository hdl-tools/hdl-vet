"""Test helper for phase 2: a small three-level design written to a temp dir.

Layout:  <root>/design.f, <root>/rtl/{leaf,alt_leaf,mid,top}.sv
Hierarchy: top -> u_mid (mid) -> u_l0, u_l1 (leaf); top -> u_spare (leaf).

`top.sv` starts with a two-line generator banner and deliberately connects
`u_spare.q` to an undeclared signal, so the baseline has at least one warning.
`alt_leaf` is never instantiated; it exists as a wrong-port swap target.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

LEAF = (
    "module leaf #(\n"
    "  parameter int WIDTH = 4,\n"
    "  parameter int DEPTH = 2\n"
    ") (\n"
    "  input  logic             clk,\n"
    "  input  logic [WIDTH-1:0] d,\n"
    "  output logic [WIDTH-1:0] q\n"
    ");\n"
    "  always_ff @(posedge clk) q <= d;\n"
    "endmodule\n"
)

ALT_LEAF = (
    "module alt_leaf (\n"
    "  input  logic       clk,\n"
    "  input  logic [3:0] din,\n"
    "  output logic [3:0] q\n"
    ");\n"
    "  always_ff @(posedge clk) q <= din;\n"
    "endmodule\n"
)

MID = (
    "module mid (\n"
    "  input  logic       clk,\n"
    "  input  logic [3:0] a,\n"
    "  output logic [3:0] y0, y1\n"
    ");\n"
    "  leaf #(.WIDTH(4)) u_l0 (.clk(clk), .d(a), .q(y0));\n"
    "  leaf #(.WIDTH(4), .DEPTH(3)) u_l1 (\n"
    "    .clk (clk),\n"
    "    .d   (a),\n"
    "    .q   (y1)\n"
    "  );\n"
    "endmodule\n"
)

TOP = (
    "// Generated by a generator. Do not edit.\n"
    "// sha256: 0000\n"
    "\n"
    "module top (\n"
    "  input  logic       clk,\n"
    "  input  logic [3:0] a,\n"
    "  output logic [3:0] y0,\n"
    "  output logic [3:0] y1\n"
    ");\n"
    "  logic [3:0] spare_d;\n"
    "  assign spare_d = a;\n"
    "  mid u_mid (.clk(clk), .a(a), .y0(y0), .y1(y1));\n"
    "  leaf u_spare (.clk(clk), .d(spare_d), .q(spare_q));\n"
    "endmodule\n"
)

FILELIST = "rtl/leaf.sv\nrtl/alt_leaf.sv\nrtl/mid.sv\nrtl/top.sv\n"


@dataclass(frozen=True)
class Kit:
    root: Path
    filelist: Path
    leaf: Path
    alt_leaf: Path
    mid: Path
    top: Path

    @property
    def sources(self) -> list[Path]:
        return [self.leaf, self.alt_leaf, self.mid, self.top]


def make_design(root: Path, newline: str = "\n") -> Kit:
    """Write the design under `root` (created if needed) and return its paths."""
    root = Path(root).resolve()
    rtl = root / "rtl"
    rtl.mkdir(parents=True, exist_ok=True)
    for name, text in (("leaf", LEAF), ("alt_leaf", ALT_LEAF), ("mid", MID), ("top", TOP)):
        (rtl / f"{name}.sv").write_bytes(text.replace("\n", newline).encode())
    (root / "design.f").write_bytes(FILELIST.encode())
    return Kit(root, root / "design.f", rtl / "leaf.sv", rtl / "alt_leaf.sv", rtl / "mid.sv", rtl / "top.sv")


def span(data: bytes, needle: bytes, nth: int = 0) -> tuple[int, int]:
    """Byte range of the nth occurrence of `needle` in `data`."""
    pos = -1
    for _ in range(nth + 1):
        pos = data.index(needle, pos + 1)
    return pos, pos + len(needle)


def tree_bytes(root: Path) -> dict[str, bytes]:
    """Every file under `root`, keyed by POSIX relative path."""
    root = Path(root)
    return {p.relative_to(root).as_posix(): p.read_bytes() for p in sorted(root.rglob("*")) if p.is_file()}
